/**
 * 恢复 Capacitor Cordova 构建文件（P4-2B 收官收尾）。
 *
 * 背景：本机 `npx cap sync android` 的收尾删除步骤会因环境删除工具
 * （genie-trash）超时失败，导致 `capacitor-cordova-android-plugins/`
 * 下的 cordova.variables.gradle 与 build.gradle 缺失，Android 构建
 * 中断。本脚本内置 Capacitor 官方模板内容（提取自
 * node_modules/@capacitor/cli/assets/capacitor-cordova-android-plugins
 * .tar.gz），使 `cap sync → Android build` 在干净检出上可复现——
 * 不依赖手工恢复未跟踪文件、不依赖外部解压工具。
 *
 * 用法：node scripts/ensure-android-cordova-files.mjs
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const pluginsDir = path.join(root, 'android', 'capacitor-cordova-android-plugins')

function log(message) {
  console.log(`[ensure-cordova] ${message}`)
}

/** Capacitor 官方模板：capacitor-cordova-android-plugins/build.gradle */
const TEMPLATE_BUILD_GRADLE = String.raw`ext {
    androidxAppCompatVersion = project.hasProperty('androidxAppCompatVersion') ? rootProject.ext.androidxAppCompatVersion : '1.7.0'
    cordovaAndroidVersion = project.hasProperty('cordovaAndroidVersion') ? rootProject.ext.cordovaAndroidVersion : '10.1.1'
}

buildscript {
    repositories {
        google()
        mavenCentral()
    }
    dependencies {
        classpath 'com.android.tools.build:gradle:8.7.2'
    }
}

apply plugin: 'com.android.library'

android {
    namespace "capacitor.cordova.android.plugins"
    compileSdk project.hasProperty('compileSdkVersion') ? rootProject.ext.compileSdkVersion : 35
    defaultConfig {
        minSdkVersion project.hasProperty('minSdkVersion') ? rootProject.ext.minSdkVersion : 23
        targetSdkVersion project.hasProperty('targetSdkVersion') ? rootProject.ext.targetSdkVersion : 35
        versionCode 1
        versionName "1.0"
    }
    lintOptions {
        abortOnError false
    }
    compileOptions {
        sourceCompatibility JavaVersion.VERSION_21
        targetCompatibility JavaVersion.VERSION_21
    }
}

repositories {
    google()
    mavenCentral()
    flatDir{
        dirs 'src/main/libs', 'libs'
    }
}

dependencies {
    implementation fileTree(dir: 'src/main/libs', include: ['*.jar'])
    implementation "androidx.appcompat:appcompat:$androidxAppCompatVersion"
    implementation "org.apache.cordova:framework:$cordovaAndroidVersion"
    // SUB-PROJECT DEPENDENCIES START
    
    // SUB-PROJECT DEPENDENCIES END
}

// PLUGIN GRADLE EXTENSIONS START

// PLUGIN GRADLE EXTENSIONS END

for (def func : cdvPluginPostBuildExtras) {
    func()
}`

/** Capacitor 官方模板语义：cordova.variables.gradle（无 cordova 插件变量） */
const TEMPLATE_CORDOVA_VARIABLES = `// DO NOT EDIT THIS FILE! IT IS GENERATED EACH TIME "capacitor update" IS RUN
// 由 scripts/ensure-android-cordova-files.mjs 恢复（官方模板语义）。
ext {
    cdvPluginPostBuildExtras = []
}
`

fs.mkdirSync(pluginsDir, { recursive: true })

// 1) cordova.variables.gradle
const variablesPath = path.join(pluginsDir, 'cordova.variables.gradle')
if (!fs.existsSync(variablesPath)) {
  fs.writeFileSync(variablesPath, TEMPLATE_CORDOVA_VARIABLES)
  log('已恢复 cordova.variables.gradle')
} else {
  log('cordova.variables.gradle 已存在，跳过')
}

// 2) build.gradle（官方模板 + Capacitor CLI 生成时会注入的 apply 行，
//    注入位置与 CLI handleCordovaPluginsGradle 一致）
const buildPath = path.join(pluginsDir, 'build.gradle')
let buildContent = TEMPLATE_BUILD_GRADLE
if (!buildContent.includes('apply from: "cordova.variables.gradle"')) {
  buildContent = buildContent.replace(
    '// PLUGIN GRADLE EXTENSIONS END',
    '// PLUGIN GRADLE EXTENSIONS END\n\napply from: "cordova.variables.gradle"',
  )
}
if (!fs.existsSync(buildPath) || fs.readFileSync(buildPath, 'utf8') !== buildContent) {
  fs.writeFileSync(buildPath, buildContent)
  log('已恢复 build.gradle（官方模板 + apply 行）')
} else {
  log('build.gradle 已是最新，跳过')
}

log('完成。可继续: cd android && ./gradlew assembleDebug')
