import assert from 'node:assert/strict'
import crypto from 'node:crypto'

const base = new URL(process.env.PRODUCTION_SMOKE_URL || 'http://127.0.0.1:8255')
if (!['127.0.0.1', 'localhost', '[::1]'].includes(base.hostname)) throw new Error('Production smoke is restricted to an isolated loopback deployment')
const endpoint = path => new URL(path, base)
const post = (path, data, token) => fetch(endpoint(path), { method: 'POST', headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) }, body: JSON.stringify(data) })

assert.equal((await fetch(endpoint('/healthz'))).status, 200)
const image = await fetch(endpoint('/reverse-evaluation/visual-reflection-writeback.png'))
assert.equal(image.status, 200)
assert.match(image.headers.get('content-type'), /image\/png/)
assert.equal(Buffer.from(await image.arrayBuffer()).subarray(0, 8).toString('hex'), '89504e470d0a1a0a')
const health = await fetch(endpoint('/api/health'))
assert.equal(health.status, 200)
assert.equal((await health.json()).productionStorageReady, true)
for (const route of ['/api/chat/history', '/api/payments/products', '/api/payments/entitlements']) assert.equal((await fetch(endpoint(route))).status, 401, `${route} must require authentication`)
assert.equal((await post('/api/auth/login', { account: 'reviewer', password: 'Zhixue2026!', role: 'student' })).status, 401, 'production cannot use competition demo credentials')
const account = `compose-smoke-${crypto.randomBytes(8).toString('hex')}`
const password = crypto.randomBytes(24).toString('hex')
const registered = await post('/api/auth/register', { account, password, displayName: 'Isolated CI fixture', role: 'admin' })
assert.equal(registered.status, 201)
assert.equal((await registered.json()).role, 'student')
const login = await post('/api/auth/login', { account, password, role: 'admin' })
assert.equal(login.status, 200)
assert.match(login.headers.get('set-cookie'), /Secure/)
assert.match(login.headers.get('set-cookie'), /HttpOnly/)
const identity = await login.json()
assert.equal(identity.role, 'student')
assert.ok(identity.token)
const headers = { Authorization: `Bearer ${identity.token}` }
const products = await fetch(endpoint('/api/payments/products'), { headers })
assert.equal(products.status, 200)
const catalog = await products.json()
assert.equal(catalog.provider, 'vibe-pay')
assert.ok(catalog.products.every(product => product.available === false))
assert.equal((await post('/api/payments/orders', { idempotencyKey: crypto.randomUUID() }, identity.token)).status, 503, 'isolated deployment must keep sales disabled')
assert.equal((await post('/api/payments/mock/complete', {}, identity.token)).status, 404)
const returned = await fetch(endpoint('/api/payments/return?out_trade_no=untrusted-order&trade_status=TRADE_SUCCESS'))
assert.equal(returned.status, 200)
const html = await returned.text()
assert.match(html, /正在确认支付结果/); assert.ok(!html.includes('untrusted-order'))
console.log('Production Compose smoke passed: MySQL readiness, account boundaries, server-side roles, disabled sales and neutral return page. No payment initiated.')
